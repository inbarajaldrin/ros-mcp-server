def mount_points_tool():
    """Corners and centres of every box, tool frame (N, 3)."""
    pts = []
    for boxes in CAMERA_MOUNT_BOXES_TOOL.values():
        for lo, hi in boxes:
            lo, hi = np.asarray(lo), np.asarray(hi)
            pts += [(x, y, z) for x in (lo[0], hi[0]) for y in (lo[1], hi[1]) for z in (lo[2], hi[2])]
            pts.append(tuple((lo + hi) / 2))
    return np.array(pts)

