#!/usr/bin/env python3
"""Write the URDF of everything the arm carries, rooted at tool0, for RViz: the robot composite's quick changer + RG2
(taken from the fuzzydroid demo's fmb1_ros_description, the composite's own chain and meshes) plus the v3.1 camera mount
and the D415 body (assets/cell/camera_mount_v31) on the composite's rg2_base_link.

The OnRobot meshes are research-use only and are NOT in this public repo: they are read from the local description
($FMB_RG2_DESCRIPTION, default ~/fuzzydroid-films/video-assets-fuzzydroid-2026-10-26-234815/fmb1_ros_description) and
referenced by file:// path. Finger joints are fixed at their CAD pose (nothing publishes RG2 joint states on the cell).
Links are prefixed `tool_` so they never collide with the driver's or the cell RG2 description's names.

    python3 compliant_insertion_studio/scripts/make_tool_urdf.py OUT.urdf
"""
import os
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SRC = Path(os.environ.get('FMB_RG2_DESCRIPTION') or
           Path.home() / 'fuzzydroid-films' / 'video-assets-fuzzydroid-2026-10-26-234815' / 'fmb1_ros_description')
MOUNT = REPO / 'assets' / 'cell' / 'camera_mount_v31'
PREFIX = 'ur5e_0_'


def main(out):
    tree = ET.parse(SRC / 'robot.urdf')
    root = tree.getroot()
    links = {l.get('name'): l for l in root.findall('link')}
    joints = root.findall('joint')
    children = {}
    for j in joints:
        children.setdefault(j.find('parent').get('link'), []).append(j)
    keep_links, keep_joints, stack = [PREFIX + 'tool0'], [], [PREFIX + 'tool0']
    while stack:                                   # everything below tool0
        for j in children.get(stack.pop(), []):
            keep_joints.append(j)
            c = j.find('child').get('link')
            keep_links.append(c)
            stack.append(c)
    rn = lambda n: 'tool0' if n == PREFIX + 'tool0' else 'tool_' + n[len(PREFIX):]
    robot = ET.Element('robot', name='cell_tool_v31')
    robot.append(ET.Comment(' generated by compliant_insertion_studio/scripts/make_tool_urdf.py from ' + str(SRC) + ' '))
    for n in keep_links:
        l = links[n]
        new = ET.SubElement(robot, 'link', name=rn(n))
        for v in l.findall('visual'):
            for m in v.iter('mesh'):
                m.set('filename', m.get('filename').replace('package://fmb1_ros_description/', f'file://{SRC}/'))
            new.append(v)
    for j in keep_joints:
        nj = ET.SubElement(robot, 'joint', name=rn(j.get('name')), type='fixed')
        ET.SubElement(nj, 'parent', link=rn(j.find('parent').get('link')))
        ET.SubElement(nj, 'child', link=rn(j.find('child').get('link')))
        o = j.find('origin')
        ET.SubElement(nj, 'origin', xyz=o.get('xyz', '0 0 0') if o is not None else '0 0 0',
                      rpy=o.get('rpy', '0 0 0') if o is not None else '0 0 0')
    rg2 = rn(PREFIX + 'rg2_base_link')
    if rg2 not in [rn(n) for n in keep_links]:
        sys.exit(f'no {PREFIX}rg2_base_link below tool0 in {SRC}/robot.urdf')
    # v3.1 mount + D415 (rg2_base_link mm) and the CAD colour optical frame (TF-FOR-AGENT.md)
    for name, files, rgba in (('tool_camera_mount_v31', ['V31_upper_saddle_camera_tower_assembly_coordinates.stl',
                                                         'V31_lower_saddle_captive_M4_assembly_coordinates.stl'], '0.95 0.55 0.15 1'),
                              ('tool_d415_body_v31', ['D415_body_rg2_base_link.stl'], '0.55 0.57 0.6 1')):
        l = ET.SubElement(robot, 'link', name=name)
        for f in files:
            v = ET.SubElement(l, 'visual')
            g = ET.SubElement(v, 'geometry')
            ET.SubElement(g, 'mesh', filename=f'file://{MOUNT / f}', scale='0.001 0.001 0.001')
            mat = ET.SubElement(v, 'material', name=name + '_mat')
            ET.SubElement(mat, 'color', rgba=rgba)
        j = ET.SubElement(robot, 'joint', name=f'{rg2}_to_{name}', type='fixed')
        ET.SubElement(j, 'parent', link=rg2); ET.SubElement(j, 'child', link=name)
        ET.SubElement(j, 'origin', xyz='0 0 0', rpy='0 0 0')
    ET.SubElement(robot, 'link', name='tool_d415_color_optical_v31')
    j = ET.SubElement(robot, 'joint', name=f'{rg2}_to_tool_d415_color_optical_v31', type='fixed')
    ET.SubElement(j, 'parent', link=rg2); ET.SubElement(j, 'child', link='tool_d415_color_optical_v31')
    ET.SubElement(j, 'origin', xyz='0.065816 0 0.08891', rpy='2.094395 0 1.570796')
    ET.indent(robot)
    Path(out).write_text('<?xml version="1.0"?>\n' + ET.tostring(robot, encoding='unicode') + '\n')
    print(f'{out}: {len(keep_links) + 3} links from {SRC.name} + the v3.1 mount')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else '/tmp/fmb1_rviz/cell_tool_v31.urdf')
